/**
 * Build the stylesheet text (pure; used by tests and installStyles).
 *
 * @returns {string}
 */
export function buildStyles() {
  return STYLESHEET
}

/** Attribute selector used to find any previously installed stylesheet. */
const STYLE_SELECTOR = `style[${STYLE_ATTR}]`

/**
 * Install/reuse the plugin stylesheet for exactly one owner.
 *
 * Idempotent per document: any previous element carrying {@link STYLE_ATTR} is
 * removed before ours is appended, so repeated plugin loads cannot stack
 * stylesheets. The returned disposer removes only the element this call
 * installed and is itself idempotent.
 *
 * @param {Document} [doc] - document to install into; defaults to the global one.
 * @returns {() => void} idempotent disposer.
 */
export function installStyles(doc = document) {
  /** @type {Document | null} */
  let documentRef = null
  try {
    if (doc && typeof doc.querySelectorAll === 'function' && typeof doc.createElement === 'function') {
      documentRef = doc
    }
  } catch {
    documentRef = null
  }
  if (documentRef === null) return () => {}

  let root = null
  try {
    root = documentRef.head || documentRef.documentElement
  } catch {
    root = null
  }
  if (!root || typeof root.appendChild !== 'function') return () => {}

  // One stylesheet per document, whoever installed it first.
  try {
    for (const previous of Array.from(documentRef.querySelectorAll(STYLE_SELECTOR))) {
      try {
        previous.remove()
      } catch {
        // A foreign node we cannot remove is not ours to fail over.
      }
    }
  } catch {
    // querySelectorAll on a weird Document-like object: fall through and let
    // the append below decide whether this document is usable.
  }

  const style = documentRef.createElement('style')
  style.setAttribute(STYLE_ATTR, '')
  style.textContent = STYLESHEET

  try {
    root.appendChild(style)
  } catch {
    return () => {}
  }

  let disposed = false
  return function disposeStyles() {
    if (disposed) return
    disposed = true
    try {
      // Only the node this call created: if some other owner replaced it, the
      // replacement is untouched.
      style.remove()
    } catch {
      // Already detached (React re-render, document teardown): nothing to do.
    }
  }
}
